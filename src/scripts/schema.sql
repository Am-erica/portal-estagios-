
CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    perfil VARCHAR(20) NOT NULL
        CHECK (perfil IN ('ESTUDANTE', 'EMPRESA', 'ADMINISTRADOR')),
    curso VARCHAR(120),
    nome_empresa VARCHAR(150)
);

CREATE TABLE IF NOT EXISTS areas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS vagas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES usuarios(id),
    titulo VARCHAR(150) NOT NULL,
    descricao TEXT NOT NULL,
    area_id BIGINT NOT NULL REFERENCES areas(id),
    localizacao VARCHAR(150) NOT NULL,
    modalidade VARCHAR(20) NOT NULL
        CHECK (modalidade IN ('PRESENCIAL', 'REMOTA', 'HIBRIDA')),
    carga_horaria_semanal INTEGER NOT NULL
        CHECK (carga_horaria_semanal > 0),
    situacao VARCHAR(20) NOT NULL DEFAULT 'ABERTA'
        CHECK (situacao IN ('ABERTA', 'ENCERRADA'))
);

CREATE TABLE IF NOT EXISTS candidaturas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudante_id BIGINT NOT NULL REFERENCES usuarios(id),
    vaga_id BIGINT NOT NULL REFERENCES vagas(id),
    data_inscricao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT candidatura_unica UNIQUE (estudante_id, vaga_id)
);

ALTER TABLE usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE areas ENABLE ROW LEVEL SECURITY;
ALTER TABLE vagas ENABLE ROW LEVEL SECURITY;
ALTER TABLE candidaturas ENABLE ROW LEVEL SECURITY;
